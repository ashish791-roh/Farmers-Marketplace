export const getStateNames = (): string[] =>
  INDIA_STATES.map((s) => s.name).sort();

// Helper: get districts for a state
export const getDistrictsForState = (stateName: string): District[] => {
  const state = INDIA_STATES.find((s) => s.name === stateName);
  return state ? state.districts : [];
};

// Helper: get state info
export const getStateInfo = (stateName: string): IndiaState | undefined =>
  INDIA_STATES.find((s) => s.name === stateName);